export default class ProductSeeder implements Seeder {
  async run(dataSource: DataSource): Promise<void> {
    const productRepository = dataSource.getRepository(Product);

    // نقشه‌ی مسیر کامل (مثلاً «پوشاک مردانه>لباس>تیشرت») → دسته‌بندی
    const { byPath: categoryByPath } = await buildCategoryPaths(dataSource);

    let created = 0;
    let skipped = 0;
    const products: Product[] = [];

    for (const seed of PRODUCTS) {
      const category = categoryByPath.get(seed.category.join('>'));
      if (!category) {
        console.warn(
          `⚠️ دسته‌بندی یافت نشد، محصول رد شد: ${seed.category.join(' > ')}`,
        );
        skipped++;
        continue;
      }
      products.push(
        productRepository.create({
          title: seed.title,
          description: seed.description,
          price: seed.price,
          stock: seed.stock,
          categories: [category],
        }),
      );
      created++;
    }

    await productRepository.save(products);
    console.log(`✅ ${created} محصول با دسته‌بندی seed شد (${skipped} رد شد)`);
  }
}
